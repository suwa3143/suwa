package curiculum_B;

/**********************************************************************************
 * [概要] 九九の掛け算表を出力する処理
 * [詳細] for文を使って1～9の掛け算表（九九）をコンソールに出力する。
 **********************************************************************************/
public class Qes4 {

    public static void main(String[] args) {

        // 九九のタイトルを出力
        System.out.println("【九九の表示】\n");

        // 外側のfor文：1～9までの段（掛ける数）をループ
        for (int i = 1; i <= 9; i++) {

            // 内側のfor文：1～9までの数を掛けていく
            for (int j = 1; j <= 9; j++) {

                // 掛け算の結果を出力（例: 1×1=1）
                System.out.print(i + "×" + j + "=" + (i * j));

                // 結果が一桁のときにスペースを追加して桁をそろえる
                if (i * j < 10) {
                    System.out.print("   "); // 一桁のときスペース多め
                } else {
                    System.out.print("  ");
                }
            }

            // 1行出力したら改行
            System.out.println();
        }
    }
}